/**
 * Translation lookup function with English fallback
 */
export function t(key: string, locale: LocaleCode = 'en'): string {
  const dict = TRANSLATIONS[locale] || TRANSLATIONS.en;
  if (dict && dict[key]) {
    return dict[key];
  }
  // Fallback to English if missing in target locale
  if (TRANSLATIONS.en[key]) {
    return TRANSLATIONS.en[key];
  }
  // Return readable string if key missing entirely
  return key;
}
